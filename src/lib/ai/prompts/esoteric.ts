export function buildDestinyMatrixPrompt(matrixData: string, locale: 'ru' | 'uk' | 'en'): string {
  const lang = locale === 'uk' ? 'украинском' : locale === 'en' ? 'английском' : 'русском';
  return `ДАННЫЕ МАТРИЦЫ (рассчитаны программно по дате рождения — используй ТОЛЬКО их, ничего не пересчитывай и не выдумывай):
${matrixData}

ЯЗЫК: ${lang}.

ПРАВИЛА:
1. Все числа уже посчитаны. Никогда не пересчитывай арканы и не называй числа, которых нет в данных
2. Каждый аркан разбирай в связке "энергия → как проявляется в жизни → ⚠️ теневая сторона → ✨ что с этим делать"
3. Никаких шаблонов: ✗ "это указывает на", "вам следует", "вселенная посылает". ✓ "В работе это выглядит так...", "Ты замечаешь за собой..."
4. Теневая сторона аркана — не приговор, а непрожитая энергия. Пиши без запугивания
5. Каждый раздел про своё: не повторяй один и тот же смысл в разных блоках
6. НЕ используй **жирный текст** (markdown bold). Заголовки выделяй только эмодзи
7. НЕ начинай с мета-фраз ("вот ваш разбор"). Сразу в суть
8. Описывай склонности, а не приказы: не "ты должен", а "тебе свойственно"

СТРУКТУРА (1800-2300 слов):

🔯 Твоя матрица судьбы

✨ Ядро личности
Центр (Комета) — главная энергия, через которую человек проживает жизнь. Затем точки A, B, C: данность, что несёшь в мир, унаследованный талант. Как эти четыре энергии уживаются, где между ними трение.

🎯 Предназначение
Личностное, социальное и духовное предназначение. Что нужно закрыть в себе, прежде чем откроется социальная задача. Конкретные сферы и роли, а не абстракции.

💰 Денежный канал
Талант, приносящий деньги → что блокирует доход → точка денег. Конкретные способы монетизации именно этого таланта. Один честный разбор, почему деньги могут "не идти".

💞 Отношения
Талант в отношениях, что мешает, точка любви. Какой партнёр подходит по энергии, какой сценарий повторяется и как его прервать.

🌳 Родовые линии
Мужская и женская линии: какой ресурс и какая задача пришли по роду. Что человек отрабатывает за род, а что может взять как силу.

⚖️ Кармический хвост
Аркан отработки: привычный сценарий из прошлого, который тянет назад, и первый шаг выхода.

🎁 Итог
3 сильные стороны и 3 зоны роста — каждая привязана к конкретному аркану из данных. Один главный совет на ближайший год.

ПРОВЕРКА: все названные числа есть в данных, нет повторов между разделами, нет **bold**, каждый совет конкретный и выполнимый.`;
}
