function buildCardAdvicePrompt(cards: CardInfo[], question?: string): string {
  const c = cards[0];
  const rev = c.reversed ? ' (перевёрнута ↩️)' : '';
  const kw = c.keywords?.length ? ` (ключи: ${c.keywords.join(', ')})` : '';
  return `Человек просит совета карт${question ? `: "${question}"` : ''}.
Карта-совет: ${c.name}${rev}${kw}.

Это совет, не прогноз. Прямая карта — что сделать; перевёрнутая — чего не делать и какой внутренний блок снять. Масть подсказывает, где действовать: Кубки — в чувствах и разговоре, Жезлы — в поступке, Мечи — в решении и словах, Пентакли — в деле и деньгах; Старший аркан — совет про весь жизненный курс.

Три коротких блока:
**Совет** — одна ясная мысль, привязанная к ситуации.
**Чего избегать** — одна ловушка.
**Шаг** — одно действие на сегодня или завтра, конкретное настолько, чтобы его можно было сделать.
Без вступлений. Голос мудрого наставника.`;
}

function buildYearAheadPrompt(cards: CardInfo[], locale: 'ru' | 'uk' | 'en'): string {
  const tag = locale === 'uk' ? 'uk-UA' : locale === 'en' ? 'en-US' : 'ru-RU';
  const now = new Date();
  const months = Array.from({ length: 12 }, (_, i) =>
    new Date(now.getFullYear(), now.getMonth() + i, 1).toLocaleDateString(tag, { month: 'long', year: 'numeric' }),
  );
  const lines = cards.map((c, i) => {
    const rev = c.reversed ? ' (перевёрнута ↩️)' : '';
    return i === 0 ? `Карта года: ${c.name}${rev}` : `${months[i - 1]}: ${c.name}${rev}`;
  }).join('\n');
  return `Расклад «Год вперёд»: карта года и по карте на каждый из 12 месяцев, начиная с текущего.

${lines}

${TAROT_MECHANICS}

Структура:
**Карта года** — **Название**: тема года в 2-3 предложениях. Посчитай масти всех 12 месячных карт и скажи, какая сфера будет главной в году.
Затем каждый месяц: **Месяц** — **Карта** и одна-две фразы, чем он будет. Месяцы со Старшими арканами — поворотные, отметь это.
**Пики года**: 2-3 самых сильных месяца и 1 месяц, где стоит беречь силы, — одной строкой каждый.
В конце — напутствие на год одной фразой и одно действие на этот месяц.`;
}

