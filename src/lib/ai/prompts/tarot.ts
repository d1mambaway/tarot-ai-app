function buildYesNoPrompt(cards: CardInfo[], question?: string): string {
  const card = cards[0];
  const rev = card.reversed ? ' (перевёрнута ↩️)' : '';
  return `Я вытаскиваю одну карту из колоды Таро: ${card.name}${rev}. Это ответ на вопрос пользователя: ${question || 'общий вопрос'}.

Ответь по существу, 120-180 слов, три содержательных абзаца без заголовков.

Начни с прямого ответа (ДА или НЕТ, или нечто среднее), затем объясни, ЧТО карта говорит именно об этом вопросе. Используй мистический, немного загадочный тон, но не теряй ясности.

Первый абзац: прямой вывод и основание в карте. Второй: что помогает или мешает, одно условие, при котором ситуация изменится, и наблюдаемый признак. Третий: конкретное действие и чего сейчас избегать. Не повторяй прямой ответ в каждом абзаце. Не придумывай проценты вероятности.

Последняя фраза — не общий вывод, а одно конкретное действие: что сделать или сказать в первую очередь, исходя из этого ответа.`;
}

