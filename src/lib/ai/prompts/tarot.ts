function buildBaseReadingPrompt(params: {
  spreadId: string;
  spreadType: string;
  cards: CardInfo[];
  question?: string;
  locale: 'ru' | 'uk' | 'en';
}): string {
  const { spreadId, spreadType, cards, question } = params;

  switch (spreadId) {
    case 'card_of_day':
      return buildCardOfDayPrompt(cards);
    case 'yes_no':
      return buildYesNoPrompt(cards, question);
    case 'past_present_future':
      return buildPastPresentFuturePrompt(cards, question);
    case 'what_they_think':
      return buildWhatTheyThinkPrompt(cards, question);
    case 'career_money':
      return buildCareerMoneyPrompt(cards, question);
    case 'weekly':
      return buildWeeklyPrompt(cards);
    case 'monthly':
      return buildMonthlyPrompt(cards);
    case 'free_question':
      return buildFreeQuestionPrompt(cards, question);
    case 'celtic_cross':
      return buildCelticCrossPrompt(cards, question);
    case 'love_future':
      return buildLoveFuturePrompt(cards);
    case 'ex_return':
      return buildExReturnPrompt(cards, question);
    case 'two_paths':
      return buildTwoPathsPrompt(cards, question);
    case 'card_advice':
      return buildCardAdvicePrompt(cards, question);
    case 'year_ahead':
      return buildYearAheadPrompt(cards, params.locale);
    case 'new_moon':
      return buildNewMoonPrompt(cards);
    case 'full_moon':
      return buildFullMoonPrompt(cards);
    default:
      return buildGenericPrompt(spreadType, cards, question);
  }
}

/** Depth comes from distinct observations, not decorative introductions. */
export function buildReadingPrompt(params: Parameters<typeof buildBaseReadingPrompt>[0]): string {
  const base = buildBaseReadingPrompt(params);
  const { spreadId, cards } = params;
  const compact = ['yes_no', 'free_question', 'card_of_day', 'card_advice'].includes(spreadId);
  const depth = compact
    ? 'Сохрани число блоков из задания. Для совета карты ориентир 140-200 слов; для остальных коротких раскладов объём указан выше. Не сокращай ответ до лозунга.'
    : cards.length <= 5
      ? 'Для каждой позиции 3-4 предложения вместо краткого пересказа: вывод, основание в карте, проявление в ситуации или риск. Затем 1-2 абзаца общей картины и конкретного следующего шага. Ориентир 280-450 слов для трёх карт, 400-600 для четырёх-пяти.'
      : 'Сохрани все позиции и дни. Каждой дай 2-3 содержательных предложения, затем свяжи повторяющиеся темы и противоречия. Ориентир 500-850 слов; для 13 карт до 1000 слов. Не добирай объём повторением.';
  return `${base}\n\nТРЕБОВАНИЯ К СОДЕРЖАТЕЛЬНОСТИ (уточняют краткость выше):\n${depth}\nОтвечай именно на запрос. Каждое положение связывай с выпавшей картой. Примеры обозначай как возможные, не как известные факты. Не создавай проблему ради жёсткого тона. Советы должны менять реальное действие или решение, а не предлагать универсальный ритуал.`;
}
