/** Cards with their positions (and meaning keys) as prompt lines */
function positionedCards(cards: CardInfo[], positions: string[]): string {
  return cards.map((c, i) => {
    const rev = c.reversed ? ' (перевёрнута ↩️)' : '';
    const kw = c.keywords?.length ? ` — ключи: ${c.keywords.join(', ')}` : '';
    return `Карта ${i + 1} (${c.position || positions[i] || `позиция ${i + 1}`}): ${c.name}${rev}${kw}`;
  }).join('\n');
}

