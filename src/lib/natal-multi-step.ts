// ─── Main pipeline ───────────────────────────────────────────────────────────

/**
 * Generate a full natal chart interpretation via a 5-step pipeline.
 *
 * @param natalData  Formatted string from `formatNatalDataForPrompt()`
 * @param locale     `'ru'` or `'uk'`
 * @returns          Complete, reviewed natal chart interpretation
 */
export async function generateNatalChartMultiStep(
  natalData: string,
  locale: 'ru' | 'uk' | 'en' = 'ru',
): Promise<string> {
  const lang = locale === 'uk' ? 'украинском' : locale === 'en' ? 'русском' : 'русском';
  const langNote = `Пиши строго на ${lang} языке. Допустимы только: MC, ASC, IC, DC.`;
  const data = `АСТРОЛОГИЧЕСКИЕ ДАННЫЕ (рассчитано программно — используй ТОЛЬКО эти данные, ничего не выдумывай):\n${natalData}`;

  let tracker: PhraseTracker = { actions: [], risks: [], themes: [] };
  const parts: string[] = [];

  // ── Step 1 ─────────────────────────────────────────────────────────────────
  console.log('[natal-multi-step] Step 1/5 — Big Three');
  const s1 = await callGrok(
    [
      { role: 'system', content: sys1() },
      { role: 'user', content: `${langNote}\n\n${data}\n\nГенерируй Большую тройку + Синтез.` },
    ],
    2500,
  );
  tracker = extractTracker(s1, tracker);
  parts.push(s1);

  await sleep(STEP_DELAY_MS);

  // ── Step 2 ─────────────────────────────────────────────────────────────────
  console.log('[natal-multi-step] Step 2/5 — Personal Planets');
  const s2 = await callGrok(
    [
      { role: 'system', content: sys2(tracker) },
      { role: 'user', content: `${langNote}\n\n${data}\n\nГенерируй Личные планеты.` },
    ],
    3000,
  );
  tracker = extractTracker(s2, tracker);
  parts.push(s2);

  await sleep(STEP_DELAY_MS);

  // ── Step 3 ─────────────────────────────────────────────────────────────────
  console.log('[natal-multi-step] Step 3/5 — Aspects + Elements + Karma');
  const s3 = await callGrok(
    [
      { role: 'system', content: sys3(tracker) },
      { role: 'user', content: `${langNote}\n\n${data}\n\nГенерируй Аспекты, Стихии, Карму, Лилит, Ретрограды.` },
    ],
    3000,
  );
  tracker = extractTracker(s3, tracker);
  parts.push(s3);

  await sleep(STEP_DELAY_MS);

  // ── Step 4 ─────────────────────────────────────────────────────────────────
  console.log('[natal-multi-step] Step 4/5 — Career + Relationships + Portrait');
  const s4 = await callGrok(
    [
      { role: 'system', content: sys4(tracker) },
      { role: 'user', content: `${langNote}\n\n${data}\n\nГенерируй Карьеру, Отношения, Карту действий, Портрет.` },
    ],
    2500,
  );
  parts.push(s4);

  await sleep(STEP_DELAY_MS);

  // ── Step 5 — Review ────────────────────────────────────────────────────────
  console.log('[natal-multi-step] Step 5/5 — Review pass');
  const assembled = `🔮 ТОЛКОВАНИЕ НАТАЛЬНОЙ КАРТЫ\n\n${parts.join('\n\n')}`;

  const final = await callGrok(
    [
      { role: 'system', content: sysReview() },
      { role: 'user', content: `${langNote}\n\nОТРЕДАКТИРУЙ ЭТУ НАТАЛЬНУЮ КАРТУ:\n\n${assembled}` },
    ],
    8000,
  );

  console.log('[natal-multi-step] Done — all 5 steps complete');
  return final;
}
